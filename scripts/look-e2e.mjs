// Browser test of the Look picker (art styles) through the real UI (network stubbed). Usage: node scripts/look-e2e.mjs <outDir> [baseUrl]
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const [out, base = 'http://localhost:5173'] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const SB = 'https://stub.supabase.test';
const b64 = o => Buffer.from(JSON.stringify(o)).toString('base64url');
const exp = Math.floor(Date.now() / 1000) + 86400;
const jwt = `${b64({ alg: 'HS256' })}.${b64({ sub: 'u-1', role: 'authenticated', aud: 'authenticated', exp })}.sig`;
const json = (r, b) => r.fulfill({ status: 200, contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify(b) });
let failures = 0;
const check = (name, ok, extra = '') => { console.log(ok ? 'PASS' : 'FAIL', name, extra); if (!ok) failures++; };
const user = { id: 'u-1', aud: 'authenticated', role: 'authenticated', email: 'd@example.com', is_anonymous: false, app_metadata: {}, user_metadata: {}, email_confirmed_at: new Date().toISOString(), created_at: new Date().toISOString() };
const session = { access_token: jwt, refresh_token: 'r', token_type: 'bearer', expires_in: 86400, expires_at: exp, user };
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
await ctx.addInitScript(([s]) => { localStorage.setItem('sb-stub-auth-token', JSON.stringify(s)); localStorage.setItem('subwaytakes.muapi.key', 'mk_live_LOOKTESTKEY0123456789abcdef'); }, [session]);
const page = await ctx.newPage();
page.on('pageerror', e => console.log('[pageerror]', String(e).slice(0, 200)));
await page.route(`${SB}/**`, async r => { const u = r.request().url(); if (r.request().method() === 'OPTIONS') return r.fulfill({ status: 204, headers: { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': '*' } }); if (u.includes('/auth/v1/user')) return json(r, user); if (u.includes('/auth/v1/')) return json(r, { ...session, user }); if (u.includes('subwaytakes-byok')) return json(r, { balance: 5 }); if (u.includes('user_profiles')) return json(r, { id: 'u-1', credits_balance: 0, subscription_tier: 'free' }); return json(r, []); });

const prompt = async () => { await page.locator('summary', { hasText: 'Final prompt' }).click().catch(() => {}); return (await page.locator('details:has(summary:has-text("Final prompt")) p').innerText()); };
await page.goto(`${base}/create`);
await page.getByRole('button', { name: 'Take', exact: true }).click();
await page.getByTestId('look-picker').waitFor({ timeout: 25000 });
check('the Look picker shows six looks with Documentary chosen', (await page.locator('[data-look]').count()) === 6 && (await page.locator('[data-look=documentary]').getAttribute('aria-checked')) === 'true');
let p = await prompt();
check('documentary: no style sentence, same prompt as before', !/Visual style/.test(p));
await page.locator('[data-look=claymation]').click();
p = await page.locator('details:has(summary:has-text("Final prompt")) p').innerText();
check('claymation: the prompt gains the claymation style sentence', /stop-motion claymation/.test(p));
check('...and still has the one card and the no-microphone rule', /exactly ONE card/.test(p) && /only microphone/.test(p));
await page.screenshot({ path: `${out}/01-claymation.png` });
await page.waitForTimeout(800);
await page.reload();
await page.getByRole('button', { name: 'Take', exact: true }).click();
await page.getByTestId('look-picker').waitFor();
check('the look survives a reload', (await page.locator('[data-look=claymation]').getAttribute('aria-checked')) === 'true');
await page.locator('[data-look=documentary]').click();
p = await page.locator('details:has(summary:has-text("Final prompt")) p').innerText();
check('back to Documentary removes the style sentence', !/Visual style/.test(p));
await browser.close();
console.log(failures ? `\n${failures} FAILED` : '\nALL PASSED (stubbed network)');
process.exit(failures ? 1 : 0);
